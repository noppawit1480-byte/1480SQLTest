def q(v) -> str:
    """Render a Python value as a SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, Decimal)):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, datetime):
        return f"'{v:%Y-%m-%d %H:%M:%S}'"
    if isinstance(v, date):
        return f"'{v:%Y-%m-%d}'"
    return "'" + str(v).replace("'", "''") + "'"


def money(x: float) -> Decimal:
    return Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


class SqlFile:
    def __init__(self, key: str, title: str):
        self.key = key
        self.parts: list[str] = [f"-- Sample database: {title}\n-- GENERATED by app/sample_dbs/generate.py — do not edit by hand\n"]

    def raw(self, s: str):
        self.parts.append(s.strip() + "\n")

    def insert(self, table: str, cols: list[str], rows: list[tuple], chunk: int = 200):
        for i in range(0, len(rows), chunk):
            vals = ",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows[i:i + chunk])
            self.parts.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{vals};\n")

    def fix_identity(self, *tables: str):
        for t in tables:
            self.parts.append(
                f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), (SELECT max(id) FROM {t}));\n")

    def write(self):
        (OUT_DIR / f"{self.key}.sql").write_text("\n".join(self.parts), encoding="utf-8")


def rand_dt(rng: random.Random, start: date, end: date) -> datetime:
    span = (end - start).days
    d = start + timedelta(days=rng.randint(0, span))
    return datetime(d.year, d.month, d.day, rng.randint(8, 21), rng.randint(0, 59), rng.randint(0, 59))


def person(rng: random.Random) -> tuple[str, str]:
    return rng.choice(FIRST), rng.choice(LAST)


