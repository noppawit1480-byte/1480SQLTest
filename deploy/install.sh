#!/usr/bin/env bash
# SQLab backend on a fresh Ubuntu 22.04/24.04 VPS (frontend on Vercel). Run as root:
#   curl -fsSL https://raw.githubusercontent.com/noppawit1480-byte/1480SQLTest/main/deploy/install.sh -o install.sh
#   less install.sh          # read it first
#   sudo bash install.sh
# Optional: ADMIN_EMAIL=you@example.com ADMIN_PASSWORD='long-password' sudo -E bash install.sh
# Re-running is safe: existing secrets in /opt/sqlab/.env are kept; the code is updated and containers rebuilt.
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/noppawit1480-byte/1480SQLTest.git}"
DIR="${DIR:-/opt/sqlab}"
[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo bash install.sh)"; exit 1; }

echo "==> packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq git curl openssl ufw ca-certificates >/dev/null
if ! docker compose version >/dev/null 2>&1; then
  apt-get install -y -qq docker.io docker-compose-v2 >/dev/null || {
    echo "Could not install Docker from Ubuntu packages. Install Docker Engine + compose plugin (https://docs.docker.com/engine/install/ubuntu/) and re-run."; exit 1; }
fi
systemctl enable --now docker >/dev/null

echo "==> code ($DIR)"
if [ -d "$DIR/.git" ]; then git -C "$DIR" pull --ff-only; else git clone --depth 1 "$REPO_URL" "$DIR"; fi
cd "$DIR"

echo "==> configuration"
if [ ! -f .env ]; then
  IP="${PUBLIC_IP:-$(curl -4 -fsS https://api.ipify.org || hostname -I | awk '{print $1}')}"
  SITE="${SITE_ADDRESS:-${IP//./-}.sslip.io}"
  rnd() { openssl rand -hex "${1:-24}"; }
  umask 077
  cat > .env <<CONF
# generated by deploy/install.sh on $(date -u +%F) — keep private, never commit
MAIN_DB_USER=sqlab
MAIN_DB_PASSWORD=$(rnd)
MAIN_DB_NAME=sqlab
SANDBOX_ADMIN_PASSWORD=$(rnd)
SANDBOX_READER_PASSWORD=$(rnd)
SANDBOX_ROLE_SECRET=$(rnd 32)
MYSQL_ADMIN_PASSWORD=$(rnd)
TRUSTED_PROXY_SECRET=$(rnd 32)
SITE_ADDRESS=$SITE
COOKIE_SECURE=true
QUERY_TIMEOUT_MS=5000
MAX_RESULT_ROWS=1000
RATE_AUTH_PER_MIN=10
ADMIN_EMAIL=${ADMIN_EMAIL:-}
ADMIN_PASSWORD=${ADMIN_PASSWORD:-}
ASSISTANT_PROVIDER=auto
ASSISTANT_MODEL=claude-opus-5-5
ANTHROPIC_API_KEY=
ASSISTANT_AI_DAILY_LIMIT=60
CONF
  echo "    created $DIR/.env (mode 600) with random secrets"
else
  echo "    keeping existing $DIR/.env"
fi
SITE="$(grep '^SITE_ADDRESS=' .env | cut -d= -f2-)"

echo "==> firewall (SSH, HTTP, HTTPS only)"
ufw allow OpenSSH >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 443/udp >/dev/null
ufw --force enable >/dev/null

echo "==> build and start (first run takes a few minutes)"
docker compose -f docker-compose.yml -f deploy/docker-compose.vps.yml up -d --build

echo "==> waiting for https://$SITE/api/health"
for _ in $(seq 1 90); do
  curl -fsS "https://$SITE/api/health" >/dev/null 2>&1 && break
  sleep 5
done
if curl -fsS "https://$SITE/api/health" >/dev/null 2>&1; then
  echo "    backend is up over HTTPS"
else
  echo "    not reachable yet — check: docker compose -f docker-compose.yml -f deploy/docker-compose.vps.yml logs caddy backend"
fi

cat <<DONE

==========================================================================
 Backend URL : https://$SITE
 Set these two environment variables in the Vercel project (Production):
   BACKEND_URL  = https://$SITE
   PROXY_SECRET = (type "Sensitive") value of TRUSTED_PROXY_SECRET, shown by:
                  grep TRUSTED_PROXY_SECRET $DIR/.env
 Then redeploy the Vercel project.
 Backups: add to root's crontab ->  15 3 * * * $DIR/deploy/backup.sh
==========================================================================
DONE
